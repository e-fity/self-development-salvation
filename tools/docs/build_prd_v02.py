def run_set(r, size=None, bold=None, color=None, font=FONT):
    r.font.name = font
    r.font.element.rPr.rFonts.set(qn("w:eastAsia"), font)
    if size is not None:
        r.font.size = Pt(size)
    if bold is not None:
        r.bold = bold
    if color is not None:
        r.font.color.rgb = color


def para(text=None, chunks=None, size=BODY, bold=False, color=DARK, align=None,
         before=0, after=4, indent=None, keep=False, style=None):
    p = doc.add_paragraph(style=style) if style else doc.add_paragraph()
    if chunks:
        for t, b in chunks:
            r = p.add_run(t)
            run_set(r, size, b, color)
    elif text:
        r = p.add_run(text)
        run_set(r, size, bold, color)
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    if indent is not None:
        pf.left_indent = Cm(indent)
    if keep:
        pf.keep_with_next = True
    return p


