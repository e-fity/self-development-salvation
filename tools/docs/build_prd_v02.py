def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    el = OxmlElement("w:shd")
    el.set(qn("w:val"), "clear")
    el.set(qn("w:color"), "auto")
    el.set(qn("w:fill"), hexcolor)
    tcPr.append(el)


def cant_split(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:cantSplit")
    el.set(qn("w:val"), "true")
    first = None
    for child in trPr:
        if child.tag in (qn("w:trHeight"), qn("w:tblHeader")):
            first = child
            break
    if first is not None:
        first.addprevious(el)
    else:
        trPr.append(el)


def keep_next(row):
    for c in row.cells:
        for p in c.paragraphs:
            p.paragraph_format.keep_with_next = True


def table(headers, rows, widths, size=9, new_marks=None, zebra=True):
    """new_marks: set of (row_index, col_index) 需要标记为「本版新增/修改」的单元格"""
    assert abs(sum(widths) - TEXT_W) < 0.8, f"widths={sum(widths)}"
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0]
    for i, htext in enumerate(headers):
        c = hdr.cells[i]
        c.text = ""
        p = c.paragraphs[0]
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(htext)
        run_set(r, size, True, WHITE)
        shade(c, HDR_FILL)
    cant_split(hdr)
    trPr = hdr._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    th.set(qn("w:val"), "true")
    trPr.append(th)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            cells[ci].text = ""
            p = cells[ci].paragraphs[0]
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.2
            r = p.add_run(str(val))
            run_set(r, size, False, DARK)
            marked = new_marks and (ri, ci) in new_marks
            if marked:
                shade(cells[ci], NEW_FILL)
            elif zebra and ri % 2 == 1:
                shade(cells[ci], "F4F6F9")
    for row in t.rows:
        cant_split(row)
    # 短表整表不跨页；长表（>12 行）只锁表头，允许在行之间断开，避免整表被推到下一页留大片空白
    if len(t.rows) <= 9:
        for row in list(t.rows)[:-1]:
            keep_next(row)
    else:
        keep_next(hdr)
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    sp = doc.add_paragraph()
    sp.paragraph_format.space_after = Pt(2)
    sp.paragraph_format.line_spacing = 1.0
    return t


def callout(label, text, fill="FFF4E5", border="E0A458"):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]
    shade(c, fill)
    c.text = ""
    p = c.paragraphs[0]
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.3
    r1 = p.add_run(label + "  ")
    run_set(r1, 9, True, RGBColor(0x8A, 0x4B, 0x00))
    r2 = p.add_run(text)
    run_set(r2, 9, False, DARK)
    tcPr = c._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "8")
        el.set(qn("w:color"), border)
        borders.append(el)
    tcPr.append(borders)
    c.width = Cm(TEXT_W)
    sp = doc.add_paragraph()
    sp.paragraph_format.space_after = Pt(2)
    sp.paragraph_format.line_spacing = 1.0


def code(lines):
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]
    shade(c, CODE_FILL)
    c.text = ""
    first = True
    for line in lines:
        p = c.paragraphs[0] if first else c.add_paragraph()
        first = False
        pf = p.paragraph_format
        pf.space_before = Pt(0)
        pf.space_after = Pt(0)
        pf.line_spacing = 1.0
        pf.left_indent = Cm(0.15)
        r = p.add_run(line if line else " ")
        r.font.name = MONO
        for attr in ("w:eastAsia", "w:ascii", "w:hAnsi"):
            r.font.element.rPr.rFonts.set(qn(attr), MONO)
        r.font.size = Pt(8)
        r.font.color.rgb = RGBColor(0x24, 0x29, 0x2F)
        if line is not lines[-1]:
            pf.keep_with_next = True
            pf.keep_together = True
    tcPr = c._tc.get_or_add_tcPr()
    mar = OxmlElement("w:tcMar")
    for edge, v in (("top", "80"), ("bottom", "80"), ("left", "120"), ("right", "80")):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:w"), v)
        el.set(qn("w:type"), "dxa")
        mar.append(el)
    tcPr.append(mar)
    c.width = Cm(TEXT_W)
    sp = doc.add_paragraph()
    sp.paragraph_format.space_after = Pt(2)
    sp.paragraph_format.line_spacing = 1.0


